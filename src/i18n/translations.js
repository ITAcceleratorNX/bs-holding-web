/** @param {LangCode} lang */
export function langToHtml(lang) {
  if (lang === 'KZ') return 'kk';
  if (lang === 'EN') return 'en';
  return 'ru';
}

export const LANG_STORAGE_KEY = 'bs_holding_lang';

/** @returns {LangCode} */
export function readStoredLang() {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY);
    if (v === 'KZ' || v === 'EN' || v === 'RU') return v;
  } catch {
    /* ignore */
  }
  return 'RU';
}
