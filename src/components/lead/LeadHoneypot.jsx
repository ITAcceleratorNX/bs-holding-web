/**
 * Поле-ловушка для ботов.
 *
 * Пользователь его не видит и не может в него попасть: поле убрано из потока,
 * исключено из обхода табуляцией и скрыто от программ чтения с экрана.
 * Автозаполнение браузера и менеджеры паролей его тоже обходят — имя поля
 * не совпадает ни с одним стандартным типом. Значит, заполнить его может
 * только скрипт, который проходит по всем input на странице.
 *
 * Сервер отклоняет заявку, если поле пришло непустым.
 */
export default function LeadHoneypot({ value, onChange }) {
  return (
    <div aria-hidden="true" className="lead-honeypot">
      <input
        type="text"
        name="bs_extra_field"
        tabIndex={-1}
        autoComplete="off"
        value={value}
        onChange={onChange}
      />
    </div>
  );
}
