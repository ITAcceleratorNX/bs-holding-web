/**
 * Собирает карточку планировки: заголовок с комнатностью и блоком, комнатность
 * и площадь в подписи, крупный чертёж на белом фоне (`sheet`) и цену — только
 * подтверждённую. Блок в заголовке разводит две планировки с одной площадью.
 */
function buildPlan({ priceConfirmed, price, ...plan }) {
  return {
    ...plan,
    name: `${plan.rooms.replace(/\D.*/, '')}-комнатная · ${plan.block}`,
    sheet: true,
    cta: 'Подробнее о планировке',
    ...(priceConfirmed && price ? { price } : null),
  };
}

